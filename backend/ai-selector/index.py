def match_scenario(task: str) -> dict:
    task_lower = task.lower()
    for scenario in SCENARIOS:
        if any(kw in task_lower for kw in scenario["keywords"]):
            return scenario
    return DEFAULT_SCENARIO


def handler(event: dict, context) -> dict:
    """Локальный подбор тактического снаряжения по описанию задачи пользователя."""
    cors_headers = {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
    }

    if event.get('httpMethod') == 'OPTIONS':
        return {'statusCode': 200, 'headers': cors_headers, 'body': ''}

    if event.get('httpMethod') != 'POST':
        return {'statusCode': 405, 'headers': cors_headers, 'body': json.dumps({'error': 'Method not allowed'})}

    raw_body = event.get('body') or '{}'
    body = json.loads(raw_body) if isinstance(raw_body, str) else raw_body
    if isinstance(body, str):
        body = json.loads(body)
    task = body.get('task', '').strip()

    json_headers = {**cors_headers, 'Content-Type': 'application/json'}

    if not task:
        return {
            'statusCode': 400,
            'headers': json_headers,
            'body': json.dumps({'error': 'Опишите вашу задачу'}, ensure_ascii=False)
        }

    if len(task) < 3:
        return {
            'statusCode': 400,
            'headers': json_headers,
            'body': json.dumps({'error': 'Слишком короткое описание. Расскажите подробнее о задаче.'}, ensure_ascii=False)
        }

    scenario = match_scenario(task)
    catalog_map = {p["id"]: p for p in CATALOG}

    result_items = []
    for item in scenario["items"]:
        product = catalog_map.get(item["id"])
        if product:
            result_items.append({
                **product,
                "aiReason": item["reason"],
            })

    return {
        'statusCode': 200,
        'headers': json_headers,
        'body': json.dumps({
            'intro': scenario["intro"],
            'items': result_items,
            'budget': scenario.get("budget", {}),
        }, ensure_ascii=False)
    }
